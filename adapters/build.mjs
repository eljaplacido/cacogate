// Bundle each adapter into one self-contained ESM file with no imports,
// so it can be dropped into .opencode/plugin/ or .pi/extensions/ as-is.
import { build } from "esbuild";

for (const name of ["opencode", "pi"]) {
  await build({
    entryPoints: [`src/${name}.ts`],
    bundle: true,
    format: "esm",
    platform: "node",
    target: "es2022",
    outfile: `dist/${name}/cacogate.js`,
    banner: { js: `// cacogate ${name} adapter — generated by adapters/build.mjs; do not edit.` },
  });
}
console.log("built dist/opencode/cacogate.js dist/pi/cacogate.js");
